void Geometry::MakeCapsule(Geometry &geo, float half_height, float radius, uint32_t resx, uint32_t rings) {
  assert( resx > 2u && rings > 0u );
  assert( radius > 0.0f && half_height >= 0.0f );

  // The profile is parametrized by arc length: top cap, side, bottom cap.
  float const cap   = 0.5f * kPi * radius;
  float const side  = 2.0f * half_height;
  float const total = 2.0f * cap + side;

  Builder b{};
  b.grid(resx, 2u * rings + 1u, [&](float u, float v) {
    float const s = v * total;

    float radial{}, y{}, nr{}, ny{};
    if (s < cap) {                                    // top cap, pole to equator
      float const a = s / radius;
      radial = radius * std::sin(a);
      y      = half_height + radius * std::cos(a);
      nr     = std::sin(a);
      ny     = std::cos(a);
    } else if (s < cap + side) {                      // side, straight down
      radial = radius;
      y      = half_height - (s - cap);
      nr     = 1.0f;
      ny     = 0.0f;
    } else {                                          // bottom cap, equator to pole
      float const a = 0.5f * kPi + (s - cap - side) / radius;
      radial = radius * std::sin(a);
      y      = -half_height + radius * std::cos(a);
      nr     = std::sin(a);
      ny     = std::cos(a);
    }

    float const theta = u * kTwoPi;
    Vec3 const p{ radial * std::cos(theta), y, radial * std::sin(theta) };
    Vec3 const n{ nr * std::cos(theta), ny, nr * std::sin(theta) };
    return Sample{ p, n, { u, v } };
  });
  b.finish(geo);
}

