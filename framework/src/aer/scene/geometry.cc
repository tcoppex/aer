void Geometry::MakeSphere(Geometry &geo, float radius, uint32_t resx, uint32_t resy) {
  assert( resx > 2u && resy > 1u );
  assert( radius > 0.0f );

  Builder b{};
  b.grid(resx, resy, [&](float u, float v) {
    float const theta = u * kTwoPi;   // around Y
    float const phi   = v * kPi;      // from the +Y pole to the -Y pole
    Vec3 const n{ std::sin(phi) * std::cos(theta), std::cos(phi), std::sin(phi) * std::sin(theta) };
    return Sample{ Scale(n, radius), n, { u, v } };
  });
  b.finish(geo);
}

// ----------------------------------------------------------------------------

void Geometry::MakeTorus(Geometry &geo, float major_radius, float minor_radius, uint32_t resx, uint32_t resy) {
  Builder b{};
  b.grid(resx, resy, [&](float u, float v) {
    float const phi   = u * kTwoPi;   // around the major ring
    float const theta = v * kTwoPi;   // around the tube

    float const cp = std::cos(phi), sp = std::sin(phi);
    float const ct = std::cos(theta), st = std::sin(theta);

    // Tube position in the (x, y) plane, then rolled around Y.
    float const bx = ct * minor_radius + major_radius;
    float const by = st * minor_radius;

    Vec3 const p{ cp * bx, by, -sp * bx };
    Vec3 const n{ cp * ct, st, -sp * ct };
    return Sample{ p, n, { u, v } };
  });
  b.finish(geo);
}

