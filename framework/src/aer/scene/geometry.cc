void Geometry::MakeBox(Geometry &geo, float hx, float hy, float hz) {
  Vec3 const h{ hx, hy, hz };
  Builder b{};

  for (int axis = 0; axis < 3; ++axis) {
    int const ua = (axis + 1) % 3;
    int const va = (axis + 2) % 3;

    for (float sign : { -1.0f, 1.0f }) {
      b.grid(1u, 1u, [&](float u, float v) {
        Vec3 n{}, p{};
        n[axis] = sign;
        p[axis] = sign * h[axis];
        p[ua]   = (2.0f * u - 1.0f) * h[ua];
        p[va]   = (2.0f * v - 1.0f) * h[va];
        return Sample{ p, n, { u, v } };
      });
    }
  }
  b.finish(geo);
}

void Geometry::MakeCube(Geometry &geo, float size) {
  float const s = 0.5f * size;
  MakeBox(geo, s, s, s);
}

// ----------------------------------------------------------------------------

void Geometry::MakePlane(Geometry &geo, float size, uint32_t resx, uint32_t resy) {
  Builder b{};
  b.grid(resx, resy, [&](float u, float v) {
    Vec3 const p{ size * (u - 0.5f), 0.0f, size * (v - 0.5f) };
    return Sample{ p, { 0.0f, 1.0f, 0.0f }, { u, 1.0f - v } };
  });
  b.finish(geo);
}

